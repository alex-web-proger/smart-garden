#pragma once
#include <Arduino.h>

// Грядки - НАДСТРОЙКА над таблицей устройств полива (DeviceManager), а не
// отдельный тип устройства в протоколе: грядка не выходит на связь по
// ESP-NOW и не имеет своего MAC - это чисто хабовое понятие ("эта грядка
// поливается такой-то линией такого-то модуля"), нужное оператору, чтобы
// думать в терминах участка ("огурцы у забора"), а не в терминах
// "клапан 3 на устройстве #7". Поэтому BedManager устроен заметно проще
// DeviceManager - нет ни автообнаружения, ни полиморфизма (все грядки
// одного "типа"), ни LRU-вытеснения - просто маленькая таблица с
// сохранением в NVS, по образцу InstalledDeviceRecord в DeviceManager.h.
//
// ССЫЛКА НА МОДУЛЬ ПО MAC, А НЕ ПО ИНДЕКСУ: mac ниже - это MAC модуля
// полива (Device::mac), НЕ его текущий индекс в DeviceManager::devices[].
// Индекс устройства может смениться (переустановка на другой слот после
// forget, LRU-вытеснение кандидатов и т.п.) - MAC остаётся постоянным на
// всё время жизни физического устройства, поэтому именно он и хранится
// здесь. При каждом обращении (см. handleApiBeds() в hub.ino) актуальный
// idx ищется заново через deviceManager.find(mac) - тот же приём, что и в
// самом DeviceManager при разборе входящих пакетов. Наружу (в JSON
// веб-API) сам MAC НЕ отдаётся - фронтенду он не нужен, он работает с уже
// разрешённым в конкретный момент idx (см. handleApiBeds()).
#define MAX_BEDS 32
#define BED_NAME_MAX_LEN 24 // включая завершающий '\0', тот же лимит, что и у DEVICE_NAME_MAX_LEN

// Идентификаторы культур - фиксированный целочисленный набор (не свободный
// текст), то же решение, что и у DeviceType в протоколе - single source of
// truth здесь, дублируется вручную в CROP_OPTIONS на веб-странице (см.
// WebPage.h - общего enum'а между C++ и JS нет, та же ситуация, что и с
// TX_POWER_OPTIONS/CPU_FREQ_OPTIONS там же). Список рассчитан на
// расширение (см. запрос оператора) - при добавлении новой культуры
// дописывайте новое значение В КОНЕЦ и добавляйте option на веб-странице;
// НЕ переиспользуйте уже существующие числа под другую культуру - они
// могут быть сохранены в NVS у оператора.
enum CropType : uint8_t {
    CROP_CUCUMBER = 1,
    CROP_TOMATO = 2,
    CROP_RASPBERRY = 3,
};
#define CROP_TYPE_MIN 1
#define CROP_TYPE_MAX 3 // синхронизировать с последним значением CropType выше при расширении списка

struct GardenBed {
    bool used = false;                // false - слот свободен
    char name[BED_NAME_MAX_LEN] = ""; // название грядки, задаётся оператором при создании
    uint8_t cropId = CROP_CUCUMBER;   // культура - см. CropType выше
    uint8_t mac[6] = {};              // MAC модуля полива - см. большой комментарий выше про
                                       // ссылку по MAC, а не по индексу
    uint8_t valve = 1;                // номер линии (клапана) на этом модуле, 1..MAX_IRRIGATION_VALVES
};

class BedManager {
public:
    // used=false - слот свободен. Обычный массив объектов по значению (не
    // указателей, как devices[] в DeviceManager) - грядки не полиморфны и
    // не нуждаются в placement new/фиксированном хранилище под разные
    // размеры наследников, см. большой комментарий в DeviceManager.h,
    // почему там иначе.
    GardenBed beds[MAX_BEDS];

    // Восстанавливает грядки из NVS - вызвать один раз в setup(), по
    // тому же образцу, что и deviceManager.loadFromNVS().
    void loadFromNVS();

    // Сохраняет ТЕКУЩИЙ набор грядок в NVS целиком - вызывается только по
    // явному действию пользователя (добавление/изменение/удаление грядки),
    // редкое событие, цельная перезапись не создаёт проблем с износом
    // флеша (тот же принцип, что и у DeviceManager::saveToNVS()).
    void saveToNVS();

    // Добавляет новую грядку в первый свободный слот, возвращает её id
    // (индекс в beds[]) или -1, если таблица заполнена. Валидация
    // диапазонов (cropId/valve, существование и тип устройства по mac) -
    // на вызывающей стороне (см. handleApiAddBed() в hub.ino), симметрично
    // остальным *ApiSet*/*ApiAdd* обработчикам в проекте - здесь только
    // сохранение уже провалидированных значений.
    int addBed(const char *name, uint8_t cropId, const uint8_t *mac, uint8_t valve);

    // Обновляет уже существующую грядку (переименование и/или смена
    // культуры/привязки к модулю+линии) - false, если id не указывает на
    // существующую запись. Валидация - на вызывающей стороне, симметрично
    // addBed() выше.
    bool updateBed(int id, const char *name, uint8_t cropId, const uint8_t *mac, uint8_t valve);

    // Удаляет грядку - false, если id не указывает на существующую запись.
    bool deleteBed(int id);

    // true, если у КАКОЙ-НИБУДЬ ДРУГОЙ грядки (ид != excludeId) тот же mac и
    // та же valve, что и в аргументах - используется в handleApiAddBed()/
    // handleApiUpdateBed() в hub.ino, чтобы отклонять повторную привязку второй
    // грядки к той же линии даже в обход веб-интерфейса (где это уже
    // отсекается задизейбленными опциями в списке линий - см. takenValves() в
    // WebPage.h). excludeId=-1 (или любой несуществующий id) - ничего не
    // исключается, подходит для проверки при СОЗДАНИИ новой грядки.
    bool isValveTakenByOtherBed(const uint8_t *mac, uint8_t valve, int excludeId) const;

    // true, если id указывает на существующую запись (слот занят).
    bool isValid(int id) const;
};
