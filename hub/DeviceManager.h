#pragma once
#include <Arduino.h>
#include <GardenProtocol.h>
#include <type_traits>
#include "Device.h"
#include "IrrigationDevice.h"
// TODO: добавить #include "LightingDevice.h" (или др.) при появлении
// нового наследника Device - и учесть его в deviceStorageSize() ниже.

// Всё, что касается ТАБЛИЦЫ УСТРОЙСТВ Хаба, вынесено сюда из hub.ino:
// подключение/автообнаружение, установка (install), удаление (forget),
// LRU-вытеснение кандидатов, редактирование названия и
// сохранение/восстановление установленных устройств в энергонезависимой
// памяти (NVS/Preferences).
//
// Раньше install/forget были продублированы дважды каждый (Serial-команда
// и веб-API дергали одну и ту же логику независимо друг от друга) - здесь
// это один метод на каждое действие, и Serial-команды, и веб-API теперь
// вызывают одно и то же.
//
// ПОЛИМОРФНОЕ ХРАНЕНИЕ УСТРОЙСТВ: таблица хранит УКАЗАТЕЛИ на Device
// (devices[i] это Device*, nullptr - слот свободен), не объекты по
// значению - иначе виртуальные методы (handlePayload/appendJsonFields/...)
// не сработали бы: копирование наследника в массив базового типа "срезает"
// его до Device (object slicing). Поле devices оставлено ПУБЛИЧНЫМ (а не
// спрятано за геттер на каждое поле): вызывающий код (hub.ino,
// SerialCommands.cpp) в равной степени часто ЧИТАЕТ отдельные поля
// устройств (для JSON веб-API, для Serial-листинга, для кэширования
// телеметрии) - заводить сеттер/геттер под каждое поле было бы просто
// лишним слоем без выгоды. Действия, требующие соблюдения инвариантов
// класса (создание записи, вытеснение, сохранение в NVS) - остаются
// методами DeviceManager.
//
// ПОЧЕМУ НЕ ОБЫЧНЫЙ new/delete: findOrRegister() (регистрация кандидата)
// и LRU-вытеснение происходят часто - телеметрия у 30-50 узлов приходит
// раз в ~10 сек, а кандидаты (ещё не установленные устройства) могут
// подключаться/вытесняться заметно чаще при первоначальной настройке
// участка. При типичном uptime Хаба в месяцы частые new/delete объектов
// РАЗНОГО размера (IrrigationDevice сейчас, другие наследники в будущем)
// постепенно фрагментировали бы кучу ESP32 - на встраиваемой платформе
// без компактирующего GC это со временем может привести к отказу
// выделения памяти, даже если суммарного свободного места формально
// достаточно. Вместо кучи под каждый из MAX_DEVICES слотов заранее
// зарезервирован блок памяти ФИКСИРОВАННОГО размера (storage ниже), и
// registerAt()/destroyAt() создают/разрушают объект В ЭТОМ блоке через
// placement new и явный вызов деструктора - см. их реализацию в .cpp.
// Плата за это: при добавлении нового наследника Device его размер нужно
// учесть в deviceStorageSize() (см. static_assert в .cpp, который поймает
// забытое обновление на этапе компиляции, а не порчей памяти в рантайме).
//
// ПОТОКОБЕЗОПАСНОСТЬ: класс НЕ содержит никакой синхронизации (мьютексов
// и т.п.) и полагается на то, что единственный экземпляр (deviceManager
// в hub.ino) вызывается ИСКЛЮЧИТЕЛЬНО из задачи loop() - это гарантирует
// сам hub.ino: колбэк приёма ESP-NOW (задача стека Wi-Fi) не трогает
// DeviceManager напрямую, а только кладёт пакет в очередь, которую
// разбирает loop() (см. onDataRecv()/processIncomingPacket() в hub.ino).
// Если в будущем появится ещё один вызывающий код из другой задачи
// FreeRTOS (например, отдельная задача синхронизации с внешним
// сервером) - это правило нарушится, и потребуется либо тоже сводить его
// к очереди в loop(), либо добавлять синхронизацию сюда явно.

#define MAX_DEVICES 64 // с запасом над плановыми 30-50 реальными устройствами

// Верхняя граница размера ЛЮБОГО наследника Device - под неё выделяется
// каждый слот в storage[] ниже. Расширяйте список sizeof(...) здесь по
// мере появления новых наследников (LightingDevice и т.п.) - забытое
// обновление поймает static_assert в DeviceManager.cpp на этапе
// компиляции, а не порча памяти соседнего слота в рантайме.
constexpr size_t deviceStorageSize() {
    return sizeof(IrrigationDevice); // TODO: std::max(sizeof(IrrigationDevice), sizeof(LightingDevice), ...)
}

class DeviceManager {
public:
    // nullptr - слот свободен. Указатель, не объект по значению - см.
    // большой комментарий выше про полиморфное хранение.
    Device *devices[MAX_DEVICES] = {};

    DeviceManager() = default;

    // Некопируемый: копирование означало бы поверхностное копирование
    // указателей devices[] с двойным разрушением объектов, когда обе
    // копии выйдут из области видимости - осмысленной семантики
    // копирования таблице устройств не нужно (в проекте всегда ровно
    // один экземпляр - deviceManager в hub.ino).
    DeviceManager(const DeviceManager &) = delete;
    DeviceManager &operator=(const DeviceManager &) = delete;

    ~DeviceManager();

    // Восстанавливает установленные устройства ИЗ NVS - вызвать один раз
    // в setup(), ДО начала приёма ESP-NOW трафика, чтобы их слоты
    // 0..count-1 были заняты раньше, чем куда-либо попадёт что-то
    // автообнаруженное.
    void loadFromNVS();

    // Сохраняет ТЕКУЩИЙ набор installed-устройств в NVS целиком.
    // Вызывается только по явному действию пользователя (install/forget/
    // setName) - событие редкое, поэтому цельная перезапись не создаёт
    // проблем с износом флеша (в отличие от записи на каждый пакет).
    void saveToNVS();

    // Поиск по MAC среди уже известных устройств. -1, если не найдено.
    int find(const uint8_t *mac);

    // Найти устройство по MAC либо, если это первое сообщение от него,
    // зарегистрировать (подключить) - в свободный слот или, если таблица
    // полна, вытеснив самого "молчаливого" НЕ установленного кандидата
    // (LRU). Установленные устройства защищены от вытеснения - если
    // свободных/вытесняемых слотов нет, возвращает -1.
    int findOrRegister(const uint8_t *mac, uint8_t deviceType);

    // Пометить устройство установленным: защитить от LRU-вытеснения и
    // сохранить список установленных в NVS. false - если индекс не
    // указывает на существующее устройство.
    bool install(int idx);

    // Удалить устройство (установленное или кандидата) из таблицы и из
    // NVS - разрушает объект в слоте (см. destroyAt()). false - если
    // индекс не указывает на существующее устройство.
    bool forget(int idx);

    // Задать/сменить название устройства - ТОЛЬКО для уже установленного
    // (у кандидата название редактировать бессмысленно, он и так может быть
    // в любой момент вытеснен через LRU) - false, если idx не
    // существует или устройство не установлено. Имя обрезается до
    // DEVICE_NAME_MAX_LEN-1 символов. Пустая строка - валидное значение
    // (означает "название не задано" - тогда вызывающий код показывает
    // что-то вроде "Узел #idx" вместо него). Сохраняет весь список
    // установленных устройств в NVS, как install()/forget().
    bool setName(int idx, const char *newName);

    // Задать настройки автополива одного клапана (периодичность/объём/вкл/выкл) - симметрично
    // setName() выше: ТОЛЬКО для уже установленного устройства типа TYPE_IRRIGATION - для кандидата
    // или устройства другого типа нет смысла хранить такие настройки. valve - номер клапана
    // (1..MAX_IRRIGATION_VALVES, см. IrrigationDevice.h), intervalDays - 1..7, volumeDl - объём в десятых
    // литра (то есть уже переведённый из десятичного числа с веб-формы - см. handleApiSetValveSchedule()
    // в hub.ino, который делает этот пересчёт). false, если idx не существует, устройство не
    // установлено, не TYPE_IRRIGATION, или valve/intervalDays вне допустимых диапазонов. Сохраняет
    // весь список установленных устройств в NVS, как install()/forget()/setName() выше. В ОТЛИЧИЕ от
    // sendSetConfig() в hub.ino - НИЧЕГО не отправляет узлу по ESP-NOW, чисто локальная настройка
    // Хаба (см. большой комментарий у ValveSchedule в IrrigationDevice.h).
    bool setValveSchedule(int idx, int valve, uint8_t intervalDays, uint16_t volumeDl, bool autoEnabled);

    // true, если idx указывает на существующую запись (слот занят).
    bool isValid(int idx) const;

    // Serial-листинг всех известных устройств - вынесен сюда, а не
    // оставлен в hub.ino/SerialCommands.cpp, поскольку целиком опирается
    // только на internal-состояние этого класса.
    void printList() const;

private:
    // Фиксированное хранилище под объекты устройств - см. большой
    // комментарий выше ("ПОЧЕМУ НЕ ОБЫЧНЫЙ new/delete"). alignas на
    // максимальное выравнивание платформы (max_align_t), чтобы годилось
    // под placement new ЛЮБОГО наследника Device, а не только текущих.
    alignas(alignof(std::max_align_t)) uint8_t storage[MAX_DEVICES][deviceStorageSize()];

    // Конструирует устройство НУЖНОГО наследника (по deviceType, через
    // switch) прямо в storage[i] через placement new и записывает
    // указатель в devices[i]. Если в слоте i уже был какой-то объект
    // (переиспользование слота при LRU-вытеснении/загрузке из NVS в уже
    // занятый индекс) - сначала сам вызывает destroyAt(i), вызывающему
    // коду заботиться об этом не нужно.
    void registerAt(int i, const uint8_t *mac, uint8_t deviceType);

    // Вызывает деструктор объекта в слоте i (если есть) и обнуляет
    // devices[i]. НЕ освобождает саму память storage[i] - она статически
    // зарезервирована на весь срок жизни DeviceManager, освобождать
    // нечего (в отличие от обычного delete).
    void destroyAt(int i);

    // Компактная запись для хранения в NVS - только то, что нужно, чтобы
    // узнать устройство при следующей загрузке (MAC, тип, название).
    // Остальные поля Device (lastSeenTime, lastActiveValve и т.п.) -
    // оперативные, восстанавливаются из реального трафика после старта,
    // хранить их не нужно.
    struct InstalledDeviceRecord {
        uint8_t mac[6];
        uint8_t deviceType;
        char name[DEVICE_NAME_MAX_LEN];
        // Настройки автополива по клапанам (см. ValveSchedule/valveSchedules в IrrigationDevice.h) - имеют
        // смысл только для deviceType==TYPE_IRRIGATION; для прочих типов просто остаются
        // неиспользованными/занулёнными (см. saveToNVS()/loadFromNVS() в .cpp) - держать отдельный
        // вариант записи на каждый тип устройства было бы избыточной сложностью ради единственного
        // пока типа устройства со своими настройками; несколько десятков байт на запись при
        // MAX_DEVICES=64 незначительны (реально в NVS попадают только УСТАНОВЛЕННЫЕ устройства, их всегда
        // заметно меньше плановых 30-50).
        ValveSchedule valveSchedules[MAX_IRRIGATION_VALVES];
    };

    // NVS (энергонезависимая память ESP32). Имя пространства ограничено
    // 15 символами платформой.
    static const char *NVS_NAMESPACE;
    static const char *NVS_KEY_DEVICES;
};
