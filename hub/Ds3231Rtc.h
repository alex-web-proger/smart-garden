#pragma once
#include <Arduino.h>

// Минимальная работа с часами реального времени DS3231 по шине I2C -
// ТОЛЬКО то, что нужно Хабу: обнаружение микросхемы, чтение/запись
// текущего времени в виде unix-эпохи. Не претендует на замену
// полноценных библиотек (например, Adafruit RTClib) - код Хаба уже
// придерживается принципа "минимум внешних зависимостей" (см. hub.ino,
// handleApiDevices() собирает JSON вручную, без ArduinoJson) - здесь тот
// же подход, плюс на DS3231 нужен только десяток регистров.
//
// РОЛЬ В ПРОЕКТЕ: если DS3231 физически подключена к Хабу - она
// используется как АВТОНОМНЫЙ источник времени: в отличие от системных
// часов ESP32 (settimeofday()/time()), которые без внешнего RTC
// сбрасываются на 1970-01-01 при каждой перезагрузке, DS3231 держит время
// на собственной батарейке и переживает перезагрузку/отключение питания
// Хаба целиком. При этом Хаб по-прежнему синхронизируется с браузером как
// и раньше (см. handleApiSetTime() в hub.ino) - просто теперь каждая такая
// синхронизация ОДНОВРЕМЕННО записывает новое время и в DS3231 (см.
// setEpoch()), поддерживая его в актуальном состоянии на будущее. А при
// САМОМ СТАРТЕ (до первой синхронизации с браузером) Хаб, если часы
// обнаружены и их время заслуживает доверия, сразу читает время из
// DS3231 - не дожидаясь открытия веб-страницы в браузере (см. setup() в
// hub.ino).
//
// Хранимое здесь время - в той же системе, что и везде в проекте: МЕСТНОЕ
// (не UTC), без какой-либо перепроверки/пересчёта часового пояса на
// стороне Хаба (см. PROTOCOL.md §12) - микросхема просто хранит то,
// что в неё записали.
class Ds3231Rtc {
public:
    // Пытается обнаружить микросхему на шине I2C (адрес 0x68) - вызвать
    // один раз в setup(), ПОСЛЕ Wire.begin(). Возвращает true, если
    // микросхема ответила на шине.
    bool begin();

    bool isPresent() const { return present; }

    // false, если микросхема потеряла питание (сработал OSF - Oscillator
    // Stop Flag) с момента последней установки времени - в этом случае
    // текущее содержимое регистров времени не заслуживает доверия
    // (типичная ситуация: свежая микросхема без ранее заданного времени,
    // или полностью разряженная резервная батарейка). Вызывающий код
    // должен считать это сигналом "жду синхронизации с браузером", а не
    // читать getEpoch() как валidное время. Всегда возвращает false, если
    // isPresent()==false.
    bool hasReliableTime();

    // Текущее время микросхемы в виде unix-эпохи (местное, см. класс
    // выше). Возвращает 0, если микросхема не обнаружена.
    uint32_t getEpoch();

    // Записывает время в микросхему - вызывается сразу после каждой
    // успешной синхронизации с браузером (см. handleApiSetTime() в
    // hub.ino), чтобы DS3231 не отставала от последнего известного
    // "правильного" времени и хранила его дальше автономно на батарейке.
    // Попутно сбрасывает флаг OSF (потери питания) - записанное время
    // снова считается достоверным. Ничего не делает, если микросхема не
    // обнаружена.
    void setEpoch(uint32_t epoch);

private:
    bool present = false;

    static uint8_t bcdToDec(uint8_t bcd);
    static uint8_t decToBcd(uint8_t dec);

    // Регистры 0x00-0x06 (секунды..год) -> unix-эпоха и обратно.
    // Собственная реализация (алгоритм Хауарда Хиннанта для дней от
    // 1970-01-01), а не mktime()/timegm() - переносимо между платформами
    // и не зависит от TZ-настроек рантайма, которых на ESP32 без внешней
    // библиотеки часовых поясов нет (см. также currentTimeString() в
    // hub.ino/GardenNode.cpp - тот же принцип "не тащим timezone-машинерию").
    static uint32_t civilToEpoch(int year, int month, int day, int hour, int minute, int second);
    static void epochToCivil(uint32_t epoch, int &year, int &month, int &day,
                              int &hour, int &minute, int &second);
};
