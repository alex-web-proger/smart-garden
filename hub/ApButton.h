#pragma once
#include <Arduino.h>

// Простой антидребезг для одной кнопки, подтянутой к VCC и замыкаемой на
// GND при нажатии (INPUT_PULLUP, активный уровень LOW) - именно так
// подключена кнопка "BOOT" на большинстве плат ESP32 с модулем WROOM.
//
// Класс сознательно НЕ знает, что означает нажатие (включение точки
// доступа и т.п.) - это решает вызывающий код (hub.ino), реагируя на
// wasPressed(). Вынесен отдельно по той же причине, что и Ds3231Rtc -
// законченная, самостоятельная забота про конкретный кусок железа,
// которую не нужно смешивать с остальной логикой hub.ino.
class ApButton {
public:
    // pin - GPIO кнопки, debounceMs - минимальный интервал стабильного
    // чтения, прежде чем изменение уровня считается настоящим нажатием, а
    // не дребезгом контактов. Вызвать один раз в setup().
    void begin(uint8_t pin, unsigned long debounceMs = 50);

    // Вызывать в каждой итерации loop(). Возвращает true РОВНО ОДИН РАЗ
    // на каждое физическое нажатие - в момент перехода в нажатое
    // состояние (не всё время, пока кнопка удерживается, и не на
    // отпускание).
    bool wasPressed();

private:
    uint8_t pin = 0;
    unsigned long debounceMs = 50;
    int lastReading = HIGH;
    bool isPressed = false;
    unsigned long lastChangeMs = 0;
};
