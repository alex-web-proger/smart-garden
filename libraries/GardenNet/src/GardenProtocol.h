#pragma once
#include <Arduino.h>

// Радиоканал Wi-Fi, на котором работает вся ESP-NOW сеть проекта.
// ESP-NOW видит только устройства на ОДНОМ И ТОМ ЖЕ канале, поэтому
// это значение должно быть одинаковым на Хабе и на всех периферийных
// узлах.
// TODO: пока канал фиксирован. Когда Хаб будет подключаться к домашнему
// Wi-Fi (канал которого не контролируем), нужна будет рассылка реального
// канала периферии, а не константа.
#define ESPNOW_CHANNEL 1

// Все структуры пакета передаются "как есть" по радиоканалу между разными
// платформами (ESP8266 / ESP32), поэтому фиксируем выравнивание в 1 байт:
// без этого компилятор может добавить padding внутри структуры, и layout
// в памяти на разных платформах/версиях компилятора может не совпасть.
#pragma pack(push, 1)

// Типы устройств
enum DeviceType : uint8_t {
    TYPE_HUB = 0,
    TYPE_IRRIGATION = 1,
    TYPE_WEATHER = 2
};

// Типы сообщений
enum MsgType : uint8_t {
    MSG_CONFIG = 1,     // "Паспорт" устройства. Отправляется редко + сразу при загрузке.
                        // Приём MSG_CONFIG от устройства = сигнал "это устройство только
                        // что перезагрузилось", получатель должен сбросить dedup-счётчик
                        // для этого MAC (см. isNewerPacketId ниже).
    MSG_TELEMETRY = 2,  // Текущие показания, часто
    MSG_COMMAND = 3,    // Команда от Хаба к устройству ("сделай что-то ПРЯМО СЕЙЧАС",
                        // например "открой клапан N" - не переживает перезагрузку
                        // узла, в отличие от MSG_SET_CONFIG ниже)
    MSG_ACK = 4,        // Подтверждение приёма команды (и MSG_SET_CONFIG тоже, см. ниже)
    MSG_SET_CONFIG = 5  // Задать устройству НОВУЮ конфигурацию (хранимую НА САМОМ узле,
                        // переживает его перезагрузку, см. GardenProtocol.h/PROTOCOL.md).
                        // Отличается от MSG_COMMAND: то - разовое действие ("открой
                        // клапан"), это - изменение настройки самого устройства ("будь
                        // настроен так"). Узло принимает, применяет, сохраняет на себе
                        // (EEPROM у flow_node) и отвечает очередным MSG_CONFIG-эхо
                        // сразу же (не ждёт планового тика), чтобы Хаб увидел новые
                        // значения быстро (см. GardenNode::handleIncoming()).
};

// Спецификация полива (Паспорт устройства). Отправляется узлом в MSG_CONFIG -
// это ТЕКУЩИЕ значения, действующие на узле прямо сейчас (после применения
// возможного более раннего MSG_SET_CONFIG от Хаба, см. IrrigationConfigSet ниже и
// PROTOCOL.md), не компиляционная константа узла - именно поэтому весь пакет трактуется
// КАК текущая настройка, а не как аппаратный факт о плате (единственное
// исключение - has_flow_sensor, см. ниже).
struct IrrigationSpec {
    uint8_t valve_count;    // 1..5, теперь конфигурируемо с Хаба (см. MSG_SET_CONFIG)
    uint8_t has_flow_sensor;// аппаратный факт (припаян ли датчик потока) - Хаб это НЕ конфигурирует,
                             // узел определяет его сам при компиляции (HAS_FLOW_SENSOR в flow_node.ino)
    uint8_t mode;            // режим работы модуля - конфигурируемо с Хаба, как и valve_count.
                             // НЕ ПУТАТЬ с IrrigationCommand.mode ниже ("дозировка" по отдельной
                             // команде) - совпадение имён полей случайное, смысл разный:
                             //   1 - ЭКСКЛЮЗИВНЫЙ: открытие любого клапана автоматически
                             //       закрывает все остальные (исходное поведение проекта).
                             //   2 - НЕЗАВИСИМЫЙ: каждый клапан управляется отдельно, открытие
                             //       одного не влияет на остальные. См. IrrigationTelemetry.active_valves
                             //       и IrrigationCommand.action ниже, и onCommand()/onSetConfig() в
                             //       flow_node.ino.
};

// Желаемая Хабом конфигурация узла (паялоад для MSG_SET_CONFIG,
// направление Хаб -> узел, симметрично IrrigationCommand выше). Намеренно
// ОТДЕЛЬНАЯ структура от IrrigationSpec (а не переиспользована та же): у неё нет
// has_flow_sensor - узел не может сказать Хабу иметь/не иметь датчик потока,
// это аппаратный факт, который узел определяет сам. Смешивание этих двух структур
// в одну означало бы "Хаб может задать has_flow_sensor", что неверно по смыслу.
struct IrrigationConfigSet {
    uint8_t valve_count; // 1..5 - валидация диапазона НА СТОРОНЕ УЗЛА (он знает свою реальную
                          // аппаратную емкость по кол-ву распаянных GPIO, Хаб её не знает) -
                          // невалидное значение узел должен отклонить через MSG_ACK{status=1}.
    uint8_t mode;         // желаемый режим работы (1 - эксклюзивный, 2 - независимый, см.
                          // комментарий у IrrigationSpec.mode выше)
};

// Телеметрия полива
struct IrrigationTelemetry {
    // БИТОВАЯ МАСКА - бит (v-1) установлен = клапан v открыт, 0 = всё закрыто.
    // До введения режимов работы это был единственный номер открытого клапана
    // (active_valve) - теперь битовая маска, чтобы одинаково поддержать оба
    // режима: в mode=1 (эксклюзивный) узел гарантирует не более одного
    // установленного бита (см. onCommand()/onSetConfig() в flow_node.ino), в
    // mode=2 (независимый) бит может быть установлено несколько сразу (биты
    // выше valve_count всегда сброшены в 0). Получатель (Хаб/веб-интерфейс) не
    // должен предполагать "ровно один бит" - трактовать как произвольное
    // подмножество битов 0..valve_count-1.
    uint8_t active_valves;
    uint32_t current_flow;     // мл/мин
    uint32_t total_water_used; // литры (накопительно)
};

// Действие над target_valve в IrrigationCommand ниже - отдельное поле, а не
// неявное допущение через target_valve==0 (как было до введения режима 2) -
// в независимом режиме нужно уметь закрыть ОДИН конкретный клапан, не трогая
// остальные - чего было бы не выразить одним числом target_valve.
enum ValveAction : uint8_t {
    ACTION_OPEN = 0,
    ACTION_CLOSE = 1
};

// Команда управления поливом.
// Вынесена отдельно от телеметрии: "что просим сделать" и "что происходит
// сейчас" - разные по смыслу вещи, раньше делили одно поле active_valve.
struct IrrigationCommand {
    uint8_t target_valve;  // 1..N - конкретный клапан; 0 имеет смысл ТОЛЬКО вместе с
                            // action=ACTION_CLOSE (закрыть ВСЕ клапаны разом, единственный
                            // способ сделать это в обоих режимах - см. onCommand() в
                            // flow_node.ino); с action=ACTION_OPEN значение 0 бессмысленно и
                            // узлом отклоняется.
    uint8_t action;         // ValveAction - что сделать с target_valve (открыть/закрыть).
                            // На МОДУЛЕ ПОЛИВА оба действия работают ОДИНАКОВО в обоих режимах
                            // (затрагивают ТОЛЬКО свой бит в active_valves) - разница между
                            // режимами только в ACTION_OPEN (см. mode=1/2 у IrrigationSpec.mode
                            // выше и onCommand() в flow_node.ino): в mode=1 открытие дополнительно
                            // закрывает все остальные биты, в mode=2 - нет.
    uint8_t mode;           // "ДОЗИРОВКА" открытия (только для action=ACTION_OPEN): 0 - по времени
                            // (duration_sec), 1 - по объёму (volume_l). НЕ ПУТАТЬ с
                            // IrrigationSpec.mode/IrrigationConfigSet.mode выше ("режим работы
                            // устройства" 1/2, эксклюзивный/независимый) - это РАЗНЫЕ поля,
                            // случайное совпадение имён.
    uint16_t duration_sec; // сколько секунд держать клапан открытым (mode=0)
    uint16_t volume_l;     // сколько литров вылить (mode=1, требует датчика потока)
};

// Подтверждение приёма пакета (сейчас используется для MSG_COMMAND)
struct AckData {
    uint16_t acked_packet_id; // packet_id пакета, который подтверждаем
    uint8_t status;           // 0 - принято, 1 - отклонено/ошибка
};

// Payload объявления Хаба о (пере)загрузке (TYPE_HUB, MSG_CONFIG,
// broadcast). До появления синхронизации времени это сообщение было
// пустым (использовался только сам факт MSG_CONFIG для сброса dedup,
// см. isNewerPacketId ниже и PROTOCOL.md §4.3) - теперь заодно тем же
// пакетом Хаб разносит по сети своё текущее время, которое сам получил
// от браузера (см. PROTOCOL.md §12). `epoch == 0` - это ВАЛИДНОЕ значение
// "Хаб ещё сам не синхронизирован с браузером", а не ошибка - получатель
// обязан это проверять перед тем, как выставлять свои часы (см.
// GardenNode::handleIncoming()), иначе узел ошибочно перевёл бы себя на
// 1970-01-01.
struct HubAnnounce {
    uint32_t epoch; // МЕСТНОЕ время (секунды, уже со сдвигом на часовой пояс браузера,
                    // НЕ UTC - см. localEpochSeconds() в hub/WebPage.h и PROTOCOL.md §12).
                    // 0 = Хаб сам ещё не синхронизирован.
};

// ГЛАВНАЯ СТРУКТУРА ПАКЕТА
struct UniversalPacket {
    uint8_t sender_mac[6];   // КТО отправил
    uint8_t receiver_mac[6]; // КОМУ (00..00 - Хабу, FF..FF - широковещательно
                              // всем устройствам, иначе - конкретный узел)
    uint16_t packet_id;      // Номер пакета (для dedup, см. isNewerPacketId)
    uint8_t hop_count;       // Прыжки (для ретрансляторов)
    uint8_t device_type;     // DeviceType
    uint8_t msg_type;        // MsgType

    union {
        // TYPE_IRRIGATION: какое из полей валидно, зависит от msg_type
        union {
            IrrigationSpec spec;           // MSG_CONFIG
            IrrigationTelemetry telemetry; // MSG_TELEMETRY
            IrrigationCommand command;     // MSG_COMMAND
            IrrigationConfigSet configSet; // MSG_SET_CONFIG
        } irrigation;

        AckData ack; // MSG_ACK, общий для всех типов устройств
        HubAnnounce hub; // TYPE_HUB, MSG_CONFIG (announce о (пере)загрузке + время)
        // Здесь будут другие устройства (TYPE_WEATHER и т.д.)
    } payload;
};

#pragma pack(pop)

// ESP-NOW ограничивает полезную нагрузку 250 байтами - проверяем на этапе
// компиляции, чтобы будущие добавления в payload не вышли за лимит незаметно.
static_assert(sizeof(UniversalPacket) <= 250,
              "UniversalPacket превышает лимит полезной нагрузки ESP-NOW (250 байт)");

// MAC-адреса специального назначения, общие для всего протокола.
// static (а не extern) - каждая единица трансляции, подключившая этот
// заголовок, получает свою копию; для двух 6-байтных массивов это
// дешевле, чем заводить отдельный .cpp только ради extern-определения.
static const uint8_t BROADCAST_MAC[6] = {0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF}; // "всем" / радио-broadcast
static const uint8_t HUB_MAC[6] = {0x00, 0x00, 0x00, 0x00, 0x00, 0x00};       // "адресовано Хабу"

// Заполняет заголовок пакета - общая механика для ЛЮБОГО отправителя
// (Хаба или периферийного узла): кто/кому, номер по счётчику, hop_count,
// тип устройства и сообщения. packetIdCounter передаётся по ссылке и
// инкрементируется - это отдельный счётчик ИСХОДЯЩИХ пакетов у каждого
// устройства (не общий на весь проект).
//
// Раньше эта механика была продублирована почти дословно в hub.ino и в
// GardenNode.cpp - у Хаба и узла объективно разные требования к тому,
// ЧТО подставлять в receiver_mac/device_type (Хабу нужен произвольный
// MAC конкретного узла на каждый вызов, узлу - всегда фиксированный
// HUB_MAC), но сам процесс заполнения полей одинаков у обоих. Разная
// вызывающая логика (hub.ino::prepareHeader и GardenNode::prepareHeader)
// сохраняется - меняется только то, что они больше не дублируют тело.
inline void fillPacketHeader(UniversalPacket &pkt, const uint8_t senderMac[6],
                              const uint8_t receiverMac[6], DeviceType deviceType,
                              MsgType msgType, uint16_t &packetIdCounter) {
    memcpy(pkt.sender_mac, senderMac, 6);
    memcpy(pkt.receiver_mac, receiverMac, 6);
    pkt.packet_id = ++packetIdCounter;
    pkt.hop_count = 0;
    pkt.device_type = deviceType;
    pkt.msg_type = msgType;
}

// Циклическое сравнение packet_id (аналог сравнения TCP sequence numbers).
// Корректно обрабатывает переполнение uint16_t (65535 -> 0): считает пакет
// "новее", если разница по модулю 65536 меньше половины диапазона, и
// строго отклоняет точное совпадение (diff==0) как дубликат.
//
// Правило "MSG_CONFIG сбрасывает dedup" реализовано в обе стороны на
// уровне приложения (GardenNode - для узлов, hub.ino - для Хаба), не
// здесь: получив MSG_CONFIG от устройства, нужно сбросить сохранённый
// lastSeen packet_id для этого отправителя в 0 ДО вызова этой функции.
inline bool isNewerPacketId(uint16_t incoming, uint16_t lastSeen) {
    uint16_t diff = incoming - lastSeen;
    return diff != 0 && diff < 0x8000;
}
